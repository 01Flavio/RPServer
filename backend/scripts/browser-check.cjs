// Optional acceptance check: isolated temporary server/data and independent browser contexts.
const { chromium } = require("playwright")
const { spawn } = require("node:child_process")
const { once } = require("node:events")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const os = require("node:os")

async function main() {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), "platform-browser-"))
    const artifacts = process.env.BROWSER_ARTIFACT_DIR || directory
    fs.mkdirSync(artifacts, { recursive: true })
    const key = "ephemeral-browser-check-master-key"
    const server = spawn(process.execPath, [path.join(__dirname, "../server.js")], {
        env: { ...process.env, PORT: "3197", RPSERVER_GM_KEY: key, RPSERVER_DATA_DIR: directory }, stdio: ["ignore", "pipe", "inherit"]
    })
    let browser
    const errors = []
    try {
        await Promise.race([once(server.stdout, "data"), once(server, "exit").then(([code]) => { throw new Error(`Server exited: ${code}`) })])
        browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] })
        async function page(viewport = { width: 1440, height: 1100 }) {
            const context = await browser.newContext({ viewport })
            const page = await context.newPage()
            page.on("pageerror", (error) => errors.push(error.message))
            page.on("dialog", (dialog) => dialog.accept())
            await page.goto("http://127.0.0.1:3197/")
            await page.waitForFunction(() => document.getElementById("connection").textContent === "Conectado")
            return page
        }
        async function snapshot(page, name) {
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${name}: horizontal overflow`)
            await page.screenshot({ path: path.join(artifacts, `${name}.png`), fullPage: true })
        }
        const gm = await page()
        await snapshot(gm, "platform-entrance")
        await gm.locator("#gmMode").click()
        await gm.locator('#joinForm [name="key"]').fill(key)
        await gm.locator("#accessButton").click()
        await gm.locator("#masterWelcome").waitFor({ state: "visible" })
        await gm.locator("#campaigns button").click()
        await gm.locator("#createDialog").waitFor({ state: "visible" })
        await snapshot(gm, "platform-create-campaign")
        await gm.locator('#createForm button[type="submit"]').click()
        await gm.locator("#table").waitFor({ state: "visible" })
        assert.equal(await gm.locator("#characters button").count(), 5)
        await snapshot(gm, "platform-master-map")
        // Root map keeps pointer and keyboard movement and persists into the same state as sheets.
        await gm.locator("#map").click({ position: { x: 150, y: 180 } })
        await gm.waitForFunction(() => state.tokens.length === 1)
        await gm.locator("#map").press("ArrowRight")
        await gm.locator("#characters button").first().click()
        await gm.locator("#invite").click()
        await gm.waitForFunction(() => document.getElementById("inviteOutput").textContent.includes("Código:"))
        const invitation = (await gm.locator("#inviteOutput").textContent()).match(/Código: (\S+)/)[1]
        await gm.locator("#characters button").nth(1).click()
        await gm.locator("#characters button").first().click()
        await snapshot(gm, "platform-master-sheet")
        const player = await page({ width: 390, height: 844 })
        await snapshot(player, "platform-entrance-mobile")
        await player.locator('#joinForm [name="sessionId"]').fill("nocturne")
        await player.locator('#joinForm [name="characterId"]').fill("alex")
        await player.locator('#joinForm [name="key"]').fill(invitation)
        await player.locator("#accessButton").click()
        await player.locator("#table").waitFor({ state: "visible" })
        assert.equal(await player.locator("#characters button:not(:disabled)").count(), 1)
        assert.equal(await player.locator("#settingsTab").isVisible(), false)
        await snapshot(player, "platform-player-map-mobile")
        await player.locator("#characters button").first().click()
        await player.locator('#sheetForm [name="life"]').fill("7")
        await player.locator('#sheetForm button[type="submit"]').click()
        await gm.waitForFunction(() => document.querySelector('#sheetForm [name="life"]').value === "7")
        await player.waitForFunction(() => document.getElementById("saveStatus").textContent.includes("Salvo"))
        await gm.locator('#messageForm [name="to"]').selectOption("alex")
        await gm.locator('#messageForm [name="text"]').fill("Você ouve passos no sótão.")
        await gm.locator('#messageForm button').click()
        await player.getByText("Você ouve passos no sótão.", { exact: true }).waitFor()
        await player.locator("#roll").click()
        await gm.locator(".message.dice").waitFor()
        await player.locator('#sheetForm [name="bio"]').fill("Rascunho preservado")
        await gm.locator('#sheetForm [name="stress"]').fill("15")
        await gm.locator('#sheetForm button[type="submit"]').click()
        await player.locator("#conflict").waitFor({ state: "visible" })
        assert.equal(await player.locator('#sheetForm [name="bio"]').inputValue(), "Rascunho preservado")
        await player.locator("#reloadSheet").click()
        assert.equal(await player.locator('#sheetForm [name="stress"]').inputValue(), "15")
        await snapshot(player, "platform-player-sheet-mobile")
        await gm.locator("#settingsTab").click()
        await gm.locator('#settingsForm [name="energy"]').fill("Mana")
        await gm.locator('#settingsForm button[type="submit"]').click()
        await gm.waitForFunction(() => state.statusLabels.energy === "Mana")
        await player.waitForFunction(() => document.getElementById("energyLabel").textContent === "MANA")
        await snapshot(gm, "platform-master-settings")
        await gm.locator("#home").click()
        await gm.waitForFunction(() => document.querySelectorAll("#campaigns .campaign-card").length === 2)
        await snapshot(gm, "platform-lobby")
        await gm.locator("#newCampaign").click()
        await gm.locator('#createForm [name="title"]').fill("As crônicas do norte")
        await gm.locator('#createForm [name="id"]').fill("cronicas")
        await gm.locator('#createForm [name="system"]').fill("Fantasia d20")
        await gm.locator('#createForm button[type="submit"]').click()
        await gm.waitForFunction(() => state?.id === "cronicas")
        await gm.locator('[data-pane="sheet"]').click()
        await gm.locator("#noCharacter").waitFor({ state: "visible" })
        await gm.locator("#addCharacter").click()
        await gm.locator('#characterForm [name="name"]').fill("Luna")
        await gm.locator('#characterForm button[type="submit"]').click()
        await gm.locator("#characterName").filter({ hasText: "Luna" }).waitFor()
        await gm.locator("#diceForm [name=expression]").fill("2d6+3")
        await gm.locator("#diceForm button").click()
        await gm.locator(".message.dice").waitFor()
        await gm.locator("#removeCharacter").click()
        await gm.locator("#noCharacter").waitFor({ state: "visible" })
        // Temporary network loss re-authenticates the existing player in the original campaign.
        await player.evaluate(() => { socket.io.engine.close() })
        await player.waitForFunction(() => socket.connected && state?.id === "nocturne" && state.characters[0].stress === 15)
        assert.equal(await player.evaluate(() => localStorage.length + sessionStorage.length), 0)
        await player.locator("#home").click()
        await snapshot(player, "platform-player-lobby-mobile")
        await player.locator("#returnTable").click()
        await player.locator("#leave").click()
        await player.locator("#lobby").waitFor({ state: "visible" })
        await gm.setViewportSize({ width: 390, height: 844 })
        await gm.locator("#settingsTab").click()
        await snapshot(gm, "platform-master-settings-mobile")
        await gm.locator("#home").click()
        await snapshot(gm, "platform-master-lobby-mobile")
        await gm.locator("#logout").click()
        await gm.locator("#entrance").waitFor({ state: "visible" })
        assert.deepEqual(errors, [])
        console.log("PASS: unified entrance/lobby, campaign creation, master/player map and sheets, settings, private messages, generic dice, conflicts, dynamic characters, reconnect, logout; desktop/mobile; no page errors.")
    } finally {
        await browser?.close()
        if (server.exitCode === null && server.signalCode === null) { const exited = once(server, "exit"); server.kill(); await exited }
        fs.rmSync(directory, { recursive: true, force: true })
    }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
